import fs from 'fs';
import path from 'path';
import type { GrammarContrastIndex, GrammarPoint, GrammarTeachingOrder } from '../src/models/grammar.model';

/**
 * Writes docs/CURRICULUM.md: the full, human-readable list of what the
 * curriculum currently contains - every chapter, the points inside it, and the
 * lessons anchored to it.
 *
 * GENERATED, never hand-edited, and regenerated on every `bun run build:grammar`
 * so it cannot drift from the compiled output. That is the whole point: the
 * curriculum is 145 chapters and 96 lessons spread across three authored JSON
 * files plus two generation rules, and there was previously no single place a
 * human could read to see what actually came out the other end.
 *
 * The conceptual explanation lives in docs/GRAMMAR_TEACHING_MODEL.md, which IS
 * hand-written. This file is only the inventory.
 *
 * Run: `bun run build:curriculum-doc` (chained from `bun run build:grammar`).
 */

const POINTS_DIR = './compiled/grammar/points';
const ORDER_PATH = './compiled/grammar/index/teaching-order.json';
const CONTRASTS_PATH = './compiled/grammar/index/contrasts.json';
const OUTPUT_PATH = './docs/CURRICULUM.md';

const LEVEL_NAMES: Record<number, string> = { 5: 'N5', 4: 'N4', 3: 'N3', 2: 'N2', 1: 'N1' };

function main() {
    const order: GrammarTeachingOrder = JSON.parse(fs.readFileSync(ORDER_PATH, 'utf-8'));
    const contrasts: GrammarContrastIndex = JSON.parse(fs.readFileSync(CONTRASTS_PATH, 'utf-8'));

    const points = new Map<string, GrammarPoint>();
    for (const file of fs.readdirSync(POINTS_DIR)) {
        if (!file.endsWith('.json')) continue;
        const point: GrammarPoint = JSON.parse(fs.readFileSync(path.join(POINTS_DIR, file), 'utf-8'));
        points.set(point.id, point);
    }

    // Lessons, grouped by the chapter they are anchored to, so a chapter can
    // list the lessons that become available once it is finished.
    const lessonsByChapter = new Map<string, { familyId: string; familyName: string; title: string; points: string[]; caseCount: number }[]>();
    let lessonCount = 0;
    let caseCount = 0;
    for (const [familyId, family] of Object.entries(contrasts)) {
        for (const lesson of family.lessons) {
            lessonCount++;
            caseCount += lesson.cases.length;
            const key = lesson.taughtInChapterId ?? '(unanchored)';
            const list = lessonsByChapter.get(key) ?? [];
            list.push({ familyId, familyName: family.name, title: lesson.title, points: lesson.points, caseCount: lesson.cases.length });
            lessonsByChapter.set(key, list);
        }
    }

    const variants = [...points.values()].filter(p => p.variantOf);
    const out: string[] = [];

    out.push('# Grammar curriculum: the current contents');
    out.push('');
    out.push('> GENERATED by `scripts/build-curriculum-doc.ts` on every `bun run build:grammar`. Do not edit by hand.');
    out.push('> For what any of these words mean, read [GRAMMAR_TEACHING_MODEL.md](GRAMMAR_TEACHING_MODEL.md) first.');
    out.push('');
    out.push(`- **${order.order.length} points** introduced, across **${order.chapters.length} chapters**.`);
    out.push(`- **${variants.length} more points** are realization variants, never introduced on their own (they rotate inside their canonical's card).`);
    out.push(`- **${lessonCount} lessons** containing **${caseCount} cases**, across ${Object.keys(contrasts).length} families.`);
    const sizes = order.chapters.map(c => c.points.length).sort((a, b) => a - b);
    out.push(`- Chapter size: min ${sizes[0]}, median ${sizes[Math.floor(sizes.length / 2)]}, max ${sizes[sizes.length - 1]}.`);
    out.push('');

    out.push('## Contents by level');
    out.push('');
    out.push('| Level | Chapters | Points |');
    out.push('| --- | --- | --- |');
    for (const level of [5, 4, 3, 2, 1]) {
        const chapters = order.chapters.filter(c => c.jlptLevel === level);
        out.push(`| ${LEVEL_NAMES[level]} | ${chapters.length} | ${chapters.reduce((n, c) => n + c.points.length, 0)} |`);
    }
    out.push('');
    out.push('A chapter\'s level is its POSITION in the curriculum, not a claim about every point in it: a chapter can hold harder points that are register siblings of something it already teaches.');
    out.push('');

    out.push('## Every chapter, in teaching order');
    out.push('');

    for (const chapter of order.chapters) {
        out.push(`### ${chapter.id} (${LEVEL_NAMES[chapter.jlptLevel]}) ${chapter.title}`);
        out.push('');
        out.push(chapter.summary);
        out.push('');
        out.push('| Point | Form | Level | Family | Note |');
        out.push('| --- | --- | --- | --- | --- |');
        for (const id of chapter.points) {
            const p = points.get(id)!;
            const realizations = [...points.values()].filter(v => v.variantOf === id);
            const form = p.title + (realizations.length > 0 ? ` <br>*(also ${realizations.map(r => r.title).join(', ')})*` : '');
            const family = p.family ? `${p.family.id}${p.family.axis ? ` (${p.family.axis})` : ''}` : '';
            out.push(`| \`${id}\` | ${form} | ${LEVEL_NAMES[p.jlptLevel]} | ${family} | ${(p.usageNote ?? '').replace(/\|/g, '\\|')} |`);
        }
        out.push('');

        const lessons = lessonsByChapter.get(chapter.id);
        if (lessons) {
            out.push(`**Lessons unlocked here** (every point they compare is known by the end of this chapter):`);
            out.push('');
            for (const lesson of lessons) {
                const forms = lesson.points.map(id => points.get(id)?.title ?? id).join(' / ');
                out.push(`- **${lesson.title}** (family \`${lesson.familyId}\`, ${lesson.caseCount} case${lesson.caseCount === 1 ? '' : 's'}): ${forms}`);
            }
            out.push('');
        }
    }

    out.push('## Families with nothing to teach apart');
    out.push('');
    out.push('These have members the data marks as genuinely interchangeable. They deliberately get a note rather than a lesson: there is no rule to learn, and inventing one would be worse than saying so.');
    out.push('');
    for (const [familyId, family] of Object.entries(contrasts)) {
        if (!family.interchangeable) continue;
        out.push(`- **${family.name}** (\`${familyId}\`): ${family.interchangeable.map(id => points.get(id)?.title ?? id).join(', ')}`);
    }
    out.push('');

    fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
    fs.writeFileSync(OUTPUT_PATH, out.join('\n'));
    console.log(`📖 Curriculum inventory written to ${OUTPUT_PATH} (${order.chapters.length} chapters, ${lessonCount} lessons)`);
}

if (import.meta.main) {
    try {
        main();
    } catch (err) {
        console.error(err instanceof Error ? err.message : err);
        process.exit(1);
    }
}
